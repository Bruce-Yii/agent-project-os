import { closeDb } from "./dist/src/persistence/db.js";
import { createDb } from "./dist/src/persistence/db.js";
import { migrate } from "./dist/src/persistence/migrate.js";
import { CommandExecutor } from "./dist/src/commands/executor.js";
const url = process.env.WP1A_TEST_DB_URL;
console.log("migrating", url);
await migrate(url);
console.log("migrated");
const { db, pool } = createDb(url);
const executor = new CommandExecutor(db, { pool });
const r1 = await executor.execute({ envelope: { commandId: "rc-1", idempotencyKey: "rk-restart", actor: "personal-owner-1", personalSpaceId: "restart-ps", createdAt: new Date().toISOString(), correlationId: "rcorr", causationId: "rcause" }, intent: "BootstrapPersonalSpace", payload: { owner: "restart-owner" } });
console.log("BOOTSTRAP:", JSON.stringify(r1));
const r2 = await executor.execute({ envelope: { commandId: "rc-2", idempotencyKey: "rk-proj", actor: "personal-owner-1", personalSpaceId: "restart-ps", createdAt: new Date().toISOString(), correlationId: "rcorr2", causationId: "rcause2" }, intent: "CreateProject", payload: { space_id: "restart-ps", name: "Restart Project", goal: "g" } });
console.log("PROJECT:", JSON.stringify(r2));
await closeDb(pool);
console.log("done");
